/**
 * The casting weight tables. Philosophy (from face-variation-reference.md):
 *  - STRUCTURAL dials (face/cranial shape, cheekbone width, jaw, nose shape, eye
 *    spacing…) are left ~uniform so no two cast faces share a configuration —
 *    this is what breaks the "same AI face". They mostly don't appear below.
 *  - INCIDENTAL traits (heterochromia, vitiligo, Darwin's tubercle, deep clefts)
 *    are skewed toward their common value in GLOBAL_PRIORS so they stay rare.
 *  - Demographic signal (ancestry/age/health/sex/build) only MULTIPLIES weights
 *    as a tendency — never zeroes anything — so non-bundled combinations still
 *    occur at real frequency.
 *
 * A base weight starts at GLOBAL_PRIORS[feature][value] (or 1 if unlisted), is
 * multiplied by every active modifier table's entry (or ×1 if unlisted), then
 * normalized per feature. All weights are positive; nothing is ever 0.
 */
